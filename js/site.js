/* =========================================================
   HELPER
   ========================================================= */

function setGameText(selector, text) {

  const element =
    document.querySelector(selector);

  if (
    element &&
    typeof text === "string"
  ) {

    element.textContent = text;

  }

}


/* =========================================================
   STANDARD TRANSLATION
   ========================================================= */

function translateStandardElements(language) {

  document
    .querySelectorAll("[data-i18n]")
    .forEach(function(element) {

      const key =
        element.getAttribute("data-i18n");

      if (
        translations[language] &&
        translations[language][key] &&
        typeof translations[language][key] === "string"
      ) {

        element.textContent =
          translations[language][key];

      }

    });


  /* =======================================================
     PLACEHOLDERS
     ======================================================= */

  document
    .querySelectorAll("[data-i18n-placeholder]")
    .forEach(function(element) {

      const key =
        element.getAttribute("data-i18n-placeholder");

      if (
        translations[language] &&
        translations[language][key] &&
        typeof translations[language][key] === "string"
      ) {

        element.placeholder =
          translations[language][key];

      }

    });

}


/* =========================================================
   ROADMAP TRANSLATION
   ========================================================= */

function translateRoadmap(language) {

  const t =
    translations[language];

  if (!t) {
    return;
  }


  const lead =
    document.querySelector(".roadmap-lead");

  if (
    lead &&
    t.roadmapLead
  ) {

    lead.textContent =
      t.roadmapLead;

  }


  const motto =
    document.querySelectorAll(
      ".roadmap-motto span"
    );

  if (motto.length >= 3) {

    if (t.motto1) {
      motto[0].textContent =
        t.motto1;
    }

    if (t.motto2) {
      motto[1].textContent =
        t.motto2;
    }

    if (t.motto3) {
      motto[2].textContent =
        t.motto3;
    }

  }


  const phases =
    document.querySelectorAll(
      ".roadmap-phase"
    );

  phases.forEach(function(
    phase,
    index
  ) {

    const phaseNumber =
      index + 1;

    const titleKey =
      "phase" +
      phaseNumber +
      "Title";

    const subtitleKey =
      "phase" +
      phaseNumber +
      "Subtitle";

    const statusKey =
      "phase" +
      phaseNumber +
      "Status";

    const tasksKey =
      "phase" +
      phaseNumber +
      "Tasks";


    const title =
      phase.querySelector(
        ".roadmap-card-top h3"
      );

    const subtitle =
      phase.querySelector(
        ".roadmap-subtitle"
      );

    const status =
      phase.querySelector(
        ".roadmap-status"
      );

    const tasks =
      phase.querySelectorAll(
        ".roadmap-tasks li"
      );


    if (
      title &&
      t[titleKey]
    ) {

      title.textContent =
        t[titleKey];

    }


    if (
      subtitle &&
      t[subtitleKey]
    ) {

      subtitle.textContent =
        t[subtitleKey];

    }


    if (
      status &&
      t[statusKey]
    ) {

      status.textContent =
        t[statusKey];

    }


    if (
      t[tasksKey] &&
      Array.isArray(t[tasksKey])
    ) {

      tasks.forEach(function(
        task,
        taskIndex
      ) {

        if (
          t[tasksKey][taskIndex]
        ) {

          task.textContent =
            t[tasksKey][taskIndex];

        }

      });

    }

  });

}


