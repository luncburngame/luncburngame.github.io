    /* =======================================================
     STANDARD TRANSLATION
     ======================================================= */

  function translateStandardElements(language) {

    const t = translations[language];

    if (!t) {
      return;
    }


    /* -----------------------------------------------------
       TEXT CONTENT
       ----------------------------------------------------- */

    document
      .querySelectorAll("[data-i18n]")
      .forEach(function (element) {

        const key =
          element.getAttribute("data-i18n");

        if (
          t[key] &&
          typeof t[key] === "string"
        ) {

          element.textContent =
            t[key];

        }

      });


    /* -----------------------------------------------------
       INPUT PLACEHOLDERS
       ----------------------------------------------------- */

    document
      .querySelectorAll("[data-i18n-placeholder]")
      .forEach(function (element) {

        const key =
          element.getAttribute(
            "data-i18n-placeholder"
          );

        if (
          t[key] &&
          typeof t[key] === "string"
        ) {

          element.setAttribute(
            "placeholder",
            t[key]
          );

        }

      });

  }


  /* =======================================================
     ROADMAP TRANSLATION
     ======================================================= */

  function translateRoadmap(language) {

    const t =
      translations[language];

    if (!t) {
      return;
    }


    document
      .querySelectorAll("[data-roadmap-i18n]")
      .forEach(function (element) {

        const key =
          element.getAttribute(
            "data-roadmap-i18n"
          );

        if (
          t[key] &&
          typeof t[key] === "string"
        ) {

          element.textContent =
            t[key];

        }

      });

  }


  /* =======================================================
     GET TRANSLATION
     Used by the Contact success toaster
     ======================================================= */

  function getTranslation(
    key,
    language
  ) {

    const lang =
      language ||
      localStorage.getItem(
        "luncburngame-language"
      ) ||
      "EN";


    if (
      translations[lang] &&
      translations[lang][key]
    ) {

      return translations[lang][key];

    }


    if (
      translations.EN &&
      translations.EN[key]
    ) {

      return translations.EN[key];

    }


    return "";

  }


  /* =======================================================
     SET LANGUAGE
     ======================================================= */

  function setLanguage(language) {

    if (!translations[language]) {
      language = "EN";
    }


    /* -----------------------------------------------------
       SAVE LANGUAGE
       ----------------------------------------------------- */

    localStorage.setItem(
      "luncburngame-language",
      language
    );


    /* -----------------------------------------------------
       HTML LANGUAGE ATTRIBUTE
       ----------------------------------------------------- */

    document.documentElement.lang =
      language.toLowerCase();


    /* -----------------------------------------------------
       TRANSLATE STANDARD ELEMENTS
       ----------------------------------------------------- */

    translateStandardElements(
      language
    );


    /* -----------------------------------------------------
       TRANSLATE ROADMAP
       ----------------------------------------------------- */

    translateRoadmap(
      language
    );


    /* -----------------------------------------------------
       UPDATE LANGUAGE SELECTORS
       ----------------------------------------------------- */

    document
      .querySelectorAll(
        "[data-lang-select]"
      )
      .forEach(function (select) {

        select.value =
          language;

      });


    /* -----------------------------------------------------
       INFORM OTHER SCRIPTS
       ----------------------------------------------------- */

    document.dispatchEvent(
      new CustomEvent(
        "luncLanguageChanged",
        {
          detail: {
            language: language
          }
        }
      )
    );

  }


  /* =======================================================
     INITIALIZATION
     ======================================================= */

  document.addEventListener(
    "DOMContentLoaded",
    function () {

      /* ---------------------------------------------------
         LANGUAGE SELECTORS
         --------------------------------------------------- */

      document
        .querySelectorAll(
          "[data-lang-select]"
        )
        .forEach(function (select) {

          select.addEventListener(
            "change",
            function () {

              setLanguage(
                this.value
              );

            }
          );

        });


      /* ---------------------------------------------------
         LOAD SAVED LANGUAGE
         --------------------------------------------------- */

      const savedLanguage =
        localStorage.getItem(
          "luncburngame-language"
        ) ||
        "EN";


      setLanguage(
        savedLanguage
      );

    }
  );

