/* =========================================================
   GET TRANSLATION
   Used by other scripts
   ========================================================= */

function getTranslation(
  key,
  language
) {

  if (!language) {

    language =
      localStorage.getItem(
        "luncburngame-language"
      ) || "EN";

  }


  const lang =
    language;


  if (
    translations[lang] &&
    translations[lang][key]
  ) {

    return translations[lang][key];

  }


  if (
    translations.EN &&
    translations.EN[key]
  ) {

    return translations.EN[key];

  }


  return key;

}


/* =========================================================
   MAIN LANGUAGE FUNCTION
   ========================================================= */

function setLanguage(language) {

  if (
    !translations[language]
  ) {

    language =
      "EN";

  }


  /* Translate normal elements */

  translateStandardElements(
    language
  );


  /* Translate roadmap */

  translateRoadmap(
    language
  );


  /* Translate Contact page */

  translateContact(
    language
  );


  /* Update every language selector */

  document
    .querySelectorAll(
      "[data-lang-select]"
    )
    .forEach(function(select) {

      select.value =
        language;

    });


  /* Update HTML language */

  document.documentElement.lang =
    language.toLowerCase();


  /* Save language */

  localStorage.setItem(
    "luncburngame-language",
    language
  );


  /* Notify other scripts */

  document.dispatchEvent(
    new CustomEvent(
      "luncLanguageChanged",
      {
        detail: {
          language: language
        }
      }
    )
  );

}


/* =========================================================
   INITIALIZATION
   ========================================================= */

document.addEventListener(
  "DOMContentLoaded",
  function() {

    /* =====================================================
       LANGUAGE SELECTORS
       ===================================================== */

    document
      .querySelectorAll(
        "[data-lang-select]"
      )
      .forEach(function(select) {

        select.addEventListener(
          "change",
          function() {

            setLanguage(
              this.value
            );

          }
        );

      });


    /* =====================================================
       LOAD SAVED LANGUAGE
       ===================================================== */

    const savedLanguage =
      localStorage.getItem(
        "luncburngame-language"
      ) || "EN";


    setLanguage(
      savedLanguage
    );

  }
);


